const SIDEBAR_COOKIE_NAME = "sidebar_state"
const SIDEBAR_COOKIE_MAX_AGE = 60 * 60 * 24 * 7
const SIDEBAR_WIDTH = `${SIDEBAR_WIDTH_DEFAULT}rem`
const SIDEBAR_WIDTH_MOBILE = "18rem"
const SIDEBAR_WIDTH_ICON = "3rem"
const SIDEBAR_KEYBOARD_SHORTCUT = "b"
const REM_PX = 16

type SidebarContextProps = {
  state: "expanded" | "collapsed"
  open: boolean
  setOpen: (open: boolean) => void
  openMobile: boolean
  setOpenMobile: (open: boolean) => void
  isMobile: boolean
  toggleSidebar: () => void
  // 너비(rem). 드래그·방향키로 바꾸고 쿠키로 유지한다
  width: number
  setWidth: (width: number, persist?: boolean) => void
  resizing: boolean
  setResizing: (resizing: boolean) => void
}

const SidebarContext = React.createContext<SidebarContextProps | null>(null)

// html[data-sidebar] 는 토글할 때 이 컴포넌트가 직접 지우고 다시 그리므로 따로 구독할 것이 없다
const subscribeNoop = () => () => {}

function useSidebar() {
  const context = React.useContext(SidebarContext)
  if (!context) {
    throw new Error("useSidebar must be used within a SidebarProvider.")
  }

  return context
}

function SidebarProvider({
  defaultOpen = true,
  open: openProp,
  onOpenChange: setOpenProp,
  className,
  style,
  children,
  ...props
}: React.ComponentProps<"div"> & {
  defaultOpen?: boolean
  open?: boolean
  onOpenChange?: (open: boolean) => void
}) {
  const isMobile = useIsMobile()
  const [openMobile, setOpenMobile] = React.useState(false)

  // This is the internal state of the sidebar.
  // We use openProp and setOpenProp for control from outside the component.
  const [_open, _setOpen] = React.useState(defaultOpen)
  // 쿠키로 접어 둔 첫 페인트(layout.tsx 의 인라인 스크립트가 html[data-sidebar] 에 올린다). 서버 HTML 은 펼침이라
  // 외부 스냅숏으로 읽어 hydration 뒤에만 반영한다. 사용자가 토글하면 속성을 지워 상태만 따른다
  const restoredCollapsed = React.useSyncExternalStore(
    subscribeNoop,
    () => document.documentElement.dataset.sidebar === "collapsed",
    () => false
  )
  const open = openProp ?? (restoredCollapsed ? false : _open)
  const setOpen = React.useCallback(
    (value: boolean | ((value: boolean) => boolean)) => {
      const openState = typeof value === "function" ? value(open) : value
      delete document.documentElement.dataset.sidebar
      if (setOpenProp) {
        setOpenProp(openState)
      } else {
        _setOpen(openState)
      }

      // This sets the cookie to keep the sidebar state.
      document.cookie = `${SIDEBAR_COOKIE_NAME}=${openState}; path=/; max-age=${SIDEBAR_COOKIE_MAX_AGE}`
    },
    [setOpenProp, open]
  )

  // 너비. 첫 페인트는 인라인 스크립트가 쿠키로 html 의 --sidebar-width-user 에 올린다. 상태는 aria 값과 저장에 쓴다
  const restoredWidth = React.useSyncExternalStore(
    subscribeNoop,
    () => readSidebarWidthCookie(document.cookie),
    () => SIDEBAR_WIDTH_DEFAULT
  )
  const [userWidth, setUserWidth] = React.useState<number | null>(null)
  const [resizing, setResizing] = React.useState(false)
  const width = userWidth ?? restoredWidth
  const setWidth = React.useCallback((next: number, persist = true) => {
    const clamped = clampSidebarWidth(next)
    setUserWidth(clamped)
    document.documentElement.style.setProperty("--sidebar-width-user", `${clamped}rem`)
    if (persist) document.cookie = `${SIDEBAR_WIDTH_COOKIE}=${clamped}; path=/; max-age=${SIDEBAR_COOKIE_MAX_AGE}`
  }, [])

  // Helper to toggle the sidebar.
  const toggleSidebar = React.useCallback(() => {
    return isMobile ? setOpenMobile((open) => !open) : setOpen((open) => !open)
  }, [isMobile, setOpen, setOpenMobile])

  // Adds a keyboard shortcut to toggle the sidebar.
  React.useEffect(() => {
    const handleKeyDown = (event: KeyboardEvent) => {
      if (
        event.key === SIDEBAR_KEYBOARD_SHORTCUT &&
        (event.metaKey || event.ctrlKey)
      ) {
        event.preventDefault()
        toggleSidebar()
      }
    }

    window.addEventListener("keydown", handleKeyDown)
    return () => window.removeEventListener("keydown", handleKeyDown)
  }, [toggleSidebar])

  // We add a state so that we can do data-state="expanded" or "collapsed".
  // This makes it easier to style the sidebar with Tailwind classes.
  const state = open ? "expanded" : "collapsed"

  const contextValue = React.useMemo<SidebarContextProps>(
    () => ({
      state,
      open,
      setOpen,
      isMobile,
      openMobile,
      setOpenMobile,
      toggleSidebar,
      width,
      setWidth,
      resizing,
      setResizing,
    }),
    [state, open, setOpen, isMobile, openMobile, setOpenMobile, toggleSidebar, width, setWidth, resizing]
  )

  return (
    <SidebarContext.Provider value={contextValue}>
      <div
        data-slot="sidebar-wrapper"
        data-resizing={resizing ? "" : undefined}
        style={
          {
            // 저장된 너비(인라인 스크립트가 html 에 둔 --sidebar-width-user)가 있으면 그것, 없으면 기본값
            "--sidebar-width": `var(--sidebar-width-user, ${SIDEBAR_WIDTH})`,
            "--sidebar-width-icon": SIDEBAR_WIDTH_ICON,
            ...style,
          } as React.CSSProperties
        }
        className={cn(
          "group/sidebar-wrapper flex min-h-svh w-full has-data-[variant=inset]:bg-sidebar",
          className
        )}
        {...props}
      >
        {children}
      </div>
    </SidebarContext.Provider>
  )
}

function Sidebar({
  side = "left",
  variant = "sidebar",
  collapsible = "offcanvas",
  className,
  children,
  dir,
  ...props
}: React.ComponentProps<"div"> & {
  side?: "left" | "right"
  variant?: "sidebar" | "floating" | "inset"
  collapsible?: "offcanvas" | "icon" | "none"
}) {
  const { isMobile, state, openMobile, setOpenMobile } = useSidebar()

  if (collapsible === "none") {
    return (
      <div
        data-slot="sidebar"
        className={cn(
          "flex h-full w-(--sidebar-width) flex-col bg-sidebar text-sidebar-foreground",
          className
        )}
        {...props}
      >
        {children}
      </div>
    )
  }

  if (isMobile) {
    return (
      <Sheet open={openMobile} onOpenChange={setOpenMobile} {...props}>
        <SheetContent
          dir={dir}
          data-sidebar="sidebar"
          data-slot="sidebar"
          data-mobile="true"
          className="w-(--sidebar-width) bg-sidebar p-0 text-sidebar-foreground [&>button]:hidden"
          style={
            {
              "--sidebar-width": SIDEBAR_WIDTH_MOBILE,
            } as React.CSSProperties
          }
          side={side}
        >
          <SheetHeader className="sr-only">
            <SheetTitle>메뉴</SheetTitle>
            <SheetDescription>대화 목록과 바로가기</SheetDescription>
          </SheetHeader>
          <div className="flex h-full w-full flex-col">{children}</div>
        </SheetContent>
      </Sheet>
    )
  }

  return (
    <div
      className="group peer hidden text-sidebar-foreground md:block"
      data-state={state}
      data-collapsible={state === "collapsed" ? collapsible : ""}
      data-variant={variant}
      data-side={side}
      data-slot="sidebar"
    >
      {/* This is what handles the sidebar gap on desktop */}
      <div
        data-slot="sidebar-gap"
        className={cn(
          "relative w-(--sidebar-width) bg-transparent transition-[width] duration-200 ease-linear motion-reduce:transition-none",
          "group-data-[collapsible=offcanvas]:w-0",
          "group-data-[side=right]:rotate-180",
          variant === "floating" || variant === "inset"
            ? "group-data-[collapsible=icon]:w-[calc(var(--sidebar-width-icon)+(--spacing(4)))]"
            : "group-data-[collapsible=icon]:w-(--sidebar-width-icon)"
        )}
      />
      <div
        data-slot="sidebar-container"
        data-side={side}
        // 접힌 동안은 화면 밖에 있어도 Tab 이 들어가지 않게 inert
        inert={state === "collapsed" ? true : undefined}
        className={cn(
          "fixed inset-y-0 z-10 hidden h-svh w-(--sidebar-width) transition-[left,right,width] duration-200 ease-linear motion-reduce:transition-none data-[side=left]:left-0 data-[side=left]:group-data-[collapsible=offcanvas]:left-[calc(var(--sidebar-width)*-1)] data-[side=right]:right-0 data-[side=right]:group-data-[collapsible=offcanvas]:right-[calc(var(--sidebar-width)*-1)] md:flex",
          // Adjust the padding for floating and inset variants.
          variant === "floating" || variant === "inset"
            ? "p-2 group-data-[collapsible=icon]:w-[calc(var(--sidebar-width-icon)+(--spacing(4))+2px)]"
            : "group-data-[collapsible=icon]:w-(--sidebar-width-icon) group-data-[side=left]:border-r group-data-[side=right]:border-l",
          className
        )}
        {...props}
      >
        <div
          data-sidebar="sidebar"
          data-slot="sidebar-inner"
          className="flex size-full flex-col bg-sidebar group-data-[variant=floating]:rounded-lg group-data-[variant=floating]:shadow-sm group-data-[variant=floating]:ring-1 group-data-[variant=floating]:ring-sidebar-border"
        >
          {children}
        </div>
      </div>
    </div>
  )
}

function SidebarTrigger({
  className,
  onClick,
  ...props
}: React.ComponentProps<typeof Button>) {
  const { toggleSidebar } = useSidebar()

  return (
    <Button
      data-sidebar="trigger"
      data-slot="sidebar-trigger"
      variant="ghost"
      size="icon-sm"
      className={cn(className)}
      onClick={(event) => {
        onClick?.(event)
        toggleSidebar()
      }}
      {...props}
    >
      <PanelLeftIcon />
    </Button>
  )
}

// 사이드바 오른쪽 가장자리의 너비 조절 핸들. 드래그·방향키(1rem)·Home/End·더블클릭(기본값). 보이는 선은 hover·포커스·드래그 중에만 signal
function SidebarResizeHandle({ className, ...props }: React.ComponentProps<"div">) {
  const { width, setWidth, resizing, setResizing, isMobile, state } = useSidebar()
  if (isMobile || state === "collapsed") return null

  const toRem = (clientX: number) => clampSidebarWidth(clientX / REM_PX)

  // 드래그는 window 에서 듣는다(핸들이 폭을 따라 움직여도 끊기지 않게). 놓으면 그때 저장한다.
  // 기본 동작(글자 선택·드래그 시작)은 막고 포커스는 직접 준다(누른 뒤 방향키를 쓸 수 있게). 움직이지 않은 클릭은 너비를 바꾸지 않는다
  function startDrag(e: React.PointerEvent<HTMLDivElement>) {
    if (e.button !== 0) return
    e.preventDefault()
    e.currentTarget.focus()
    setResizing(true)
    let last: number | null = null
    const move = (ev: PointerEvent) => {
      last = ev.clientX
      setWidth(toRem(last), false)
    }
    const stop = () => {
      window.removeEventListener("pointermove", move)
      window.removeEventListener("pointerup", stop)
      window.removeEventListener("pointercancel", stop)
      setResizing(false)
      // 마지막으로 끈 자리를 저장한다(cancel 이벤트의 좌표는 0 이라 쓰지 않는다)
      if (last !== null) setWidth(toRem(last))
    }
    window.addEventListener("pointermove", move)
    window.addEventListener("pointerup", stop)
    window.addEventListener("pointercancel", stop)
  }

  function handleKeyDown(e: React.KeyboardEvent<HTMLDivElement>) {
    const next =
      e.key === "ArrowRight" ? width + SIDEBAR_WIDTH_STEP
      : e.key === "ArrowLeft" ? width - SIDEBAR_WIDTH_STEP
      : e.key === "Home" ? SIDEBAR_WIDTH_MIN
      : e.key === "End" ? SIDEBAR_WIDTH_MAX
      : null
    if (next === null) return
    e.preventDefault()
    setWidth(next)
  }

  return (
    <div
      role="separator"
      aria-orientation="vertical"
      aria-label="사이드바 너비"
      aria-valuemin={SIDEBAR_WIDTH_MIN * REM_PX}
      aria-valuemax={SIDEBAR_WIDTH_MAX * REM_PX}
      aria-valuenow={Math.round(width * REM_PX)}
      tabIndex={0}
      data-slot="sidebar-resize-handle"
      data-resizing={resizing ? "" : undefined}
      onPointerDown={startDrag}
      onDoubleClick={() => setWidth(SIDEBAR_WIDTH_DEFAULT)}
      onKeyDown={handleKeyDown}
      className={cn(
        "absolute inset-y-0 -right-1 z-20 hidden w-2 cursor-col-resize touch-none outline-none md:block",
        "after:absolute after:inset-y-0 after:left-[3px] after:w-0.5 after:bg-transparent hover:after:bg-signal focus-visible:after:bg-signal data-resizing:after:bg-signal",
        className
      )}
      {...props}
    />
  )
}

